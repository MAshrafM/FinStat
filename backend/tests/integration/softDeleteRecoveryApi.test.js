// backend/tests/integration/softDeleteRecoveryApi.test.js
const request = require('supertest');
const mongoose = require('mongoose');
const { connect, clearDatabase, closeDatabase } = require('../helpers/testDbReplSet');
const { createUserWithToken } = require('../helpers/authFixtures');
const app = require('../../server');
const Expenditure = require('../../models/Expenditure');
const Trade = require('../../models/Trade');
const RecurringBill = require('../../models/RecurringBill');

jest.setTimeout(60000);

describe('Step 7C.2a: [FEAT-006, GAP-004] Soft-Delete Recovery & Recycle Bin API Integration Tests', () => {
  let managerUser;
  let managerAuth;
  let viewerUser;
  let viewerAuth;
  let otherUser;
  let otherAuth;

  beforeAll(async () => {
    await connect();
    await Expenditure.init();
    await Trade.init();
    await RecurringBill.init();
  });

  afterAll(async () => {
    await closeDatabase();
  });

  beforeEach(async () => {
    await clearDatabase();
    await Expenditure.init();
    await Trade.init();
    await RecurringBill.init();

    const manager = await createUserWithToken({ role: 'manager', username: 'recovery_mgr' });
    managerUser = manager.user;
    managerAuth = manager.authHeader;

    const viewer = await createUserWithToken({ role: 'viewer', username: 'recovery_view', managedBy: managerUser._id });
    viewerUser = viewer.user;
    viewerAuth = viewer.authHeader;

    const other = await createUserWithToken({ role: 'manager', username: 'recovery_other' });
    otherUser = other.user;
    otherAuth = other.authHeader;
  });

  describe('1. Expenditure Soft-Delete Recovery & Option B Bridge Exclusion', () => {
    it('1. GET /api/expenditures/deleted returns soft-deleted expenditures with pagination', async () => {
      const activeExp = await Expenditure.create({
        user: managerUser._id,
        date: new Date('2026-11-01'),
        transactionValue: 200,
        transactionType: 'W',
        categories: ['Groceries'],
        paymentMethod: 'Cash',
      });

      const deletedExp = await Expenditure.create({
        user: managerUser._id,
        date: new Date('2026-11-02'),
        transactionValue: 400,
        transactionType: 'W',
        categories: ['Utilities'],
        paymentMethod: 'Bank',
        deletedAt: new Date(),
      });

      const res = await request(app)
        .get('/api/expenditures/deleted')
        .set('Authorization', managerAuth);

      expect(res.status).toBe(200);
      expect(res.body.data).toHaveLength(1);
      expect(res.body.data[0]._id.toString()).toBe(deletedExp._id.toString());
      expect(res.body.total).toBe(1);
      expect(res.body.page).toBe(1);
    });

    it('2. GET /api/expenditures/deleted excludes active (non-deleted) records', async () => {
      await Expenditure.create({
        user: managerUser._id,
        date: new Date('2026-11-01'),
        transactionValue: 500,
        transactionType: 'W',
        categories: ['Dining'],
        paymentMethod: 'Bank',
        deletedAt: null,
      });

      const res = await request(app)
        .get('/api/expenditures/deleted')
        .set('Authorization', managerAuth);

      expect(res.status).toBe(200);
      expect(res.body.data).toHaveLength(0);
      expect(res.body.total).toBe(0);
    });

    it('3. GET /api/expenditures/deleted excludes bridge-generated records (Option B) [🔴-1]', async () => {
      // Create soft-deleted manual expense
      const manualDeleted = await Expenditure.create({
        user: managerUser._id,
        date: new Date('2026-11-01'),
        transactionValue: 300,
        transactionType: 'W',
        categories: ['Other'],
        paymentMethod: 'Cash',
        deletedAt: new Date(),
      });

      // Create soft-deleted bridge expense (e.g. from paycheck or gold)
      const bridgeDeleted = await Expenditure.create({
        user: managerUser._id,
        date: new Date('2026-11-01'),
        transactionValue: 15000,
        transactionType: 'T',
        categories: ['Salary & Income'],
        paymentMethod: 'Bank',
        autoGenerated: true,
        bridgeDirection: 'inflow',
        linkedPaycheckId: new mongoose.Types.ObjectId(),
        deletedAt: new Date(),
      });

      const res = await request(app)
        .get('/api/expenditures/deleted')
        .set('Authorization', managerAuth);

      expect(res.status).toBe(200);
      expect(res.body.data).toHaveLength(1);
      expect(res.body.data[0]._id.toString()).toBe(manualDeleted._id.toString());
    });

    it('4. GET /api/expenditures/deleted includes user-confirmed bill-payment expenditures [🔴-2, 🟡-13]', async () => {
      const billPaymentDeleted = await Expenditure.create({
        user: managerUser._id,
        date: new Date('2026-11-01'),
        transactionValue: 650,
        transactionType: 'W',
        autoGenerated: false,
        bridgeDirection: null,
        linkedRecurringBillId: new mongoose.Types.ObjectId(),
        categories: ['Utilities'],
        paymentMethod: 'Bank',
        isRecurring: true,
        deletedAt: new Date(),
      });

      const res = await request(app)
        .get('/api/expenditures/deleted')
        .set('Authorization', managerAuth);

      expect(res.status).toBe(200);
      expect(res.body.data).toHaveLength(1);
      expect(res.body.data[0]._id.toString()).toBe(billPaymentDeleted._id.toString());
    });

    it('5. POST /api/expenditures/:id/restore restores soft-deleted standard expenditure and re-propagates balance deltas', async () => {
      // 1. Create baseline expenditure: seed bank +10,000
      await request(app)
        .post('/api/expenditures')
        .set('Authorization', managerAuth)
        .send({
          date: '2026-11-01',
          transactionValue: 10000,
          paymentMethod: 'Bank',
          transactionType: 'T',
          categories: ['Other'],
        });

      // 2. Create living expense on Nov 5 of 1,000
      const expRes = await request(app)
        .post('/api/expenditures')
        .set('Authorization', managerAuth)
        .send({
          date: '2026-11-05',
          transactionValue: 1000,
          paymentMethod: 'Bank',
          transactionType: 'W',
          categories: ['Groceries'],
        });
      const expId = expRes.body._id;

      // 3. Subsequent expense on Nov 10
      const subRes = await request(app)
        .post('/api/expenditures')
        .set('Authorization', managerAuth)
        .send({
          date: '2026-11-10',
          transactionValue: 500,
          paymentMethod: 'Bank',
          transactionType: 'W',
          categories: ['Dining'],
        });
      const subId = subRes.body._id;

      // Check balance before delete: 10,000 - 1,000 - 500 = 8,500
      const subBefore = await Expenditure.findById(subId);
      expect(subBefore.runningBalances.bank).toBe(8500);

      // 4. Soft-delete the Nov 5 expense
      await request(app)
        .delete(`/api/expenditures/${expId}`)
        .set('Authorization', managerAuth);

      // Balance after delete: 10,000 - 500 = 9,500
      const subAfterDelete = await Expenditure.findById(subId);
      expect(subAfterDelete.runningBalances.bank).toBe(9500);

      // 5. Restore the Nov 5 expense
      const restoreRes = await request(app)
        .post(`/api/expenditures/${expId}/restore`)
        .set('Authorization', managerAuth);

      expect(restoreRes.status).toBe(200);

      // Balance after restore re-propagates: returns to 8,500
      const subAfterRestore = await Expenditure.findById(subId);
      expect(subAfterRestore.runningBalances.bank).toBe(8500);

      // Expenditure is no longer deleted
      const restoredDoc = await Expenditure.findById(expId);
      expect(restoredDoc.deletedAt).toBeNull();
    });

    it('6. POST /api/expenditures/:id/restore rejects direct restoration of bridge record with HTTP 400 Bad Request [🔴-1]', async () => {
      const bridgeExp = await Expenditure.create({
        user: managerUser._id,
        date: new Date('2026-11-01'),
        transactionValue: 5000,
        transactionType: 'T',
        categories: ['Salary & Income'],
        paymentMethod: 'Bank',
        autoGenerated: true,
        bridgeDirection: 'inflow',
        linkedPaycheckId: new mongoose.Types.ObjectId(),
        deletedAt: new Date(),
      });

      const res = await request(app)
        .post(`/api/expenditures/${bridgeExp._id}/restore`)
        .set('Authorization', managerAuth);

      expect(res.status).toBe(400);
      expect(res.body.message).toMatch(/Cannot restore auto-generated bridge transactions/i);
    });

    it('7. POST /api/expenditures/:id/restore returns HTTP 404 for non-existent or already active expenditure', async () => {
      const activeExp = await Expenditure.create({
        user: managerUser._id,
        date: new Date('2026-11-01'),
        transactionValue: 200,
        transactionType: 'W',
        categories: ['Groceries'],
        paymentMethod: 'Bank',
        deletedAt: null,
      });

      // Active expenditure cannot be restored -> 404
      const resActive = await request(app)
        .post(`/api/expenditures/${activeExp._id}/restore`)
        .set('Authorization', managerAuth);
      expect(resActive.status).toBe(404);

      // Non-existent ID -> 404
      const fakeId = new mongoose.Types.ObjectId();
      const resFake = await request(app)
        .post(`/api/expenditures/${fakeId}/restore`)
        .set('Authorization', managerAuth);
      expect(resFake.status).toBe(404);
    });

    it('8. POST /api/expenditures/:id/restore rejects viewer role with HTTP 403 Forbidden', async () => {
      const deletedExp = await Expenditure.create({
        user: managerUser._id,
        date: new Date('2026-11-01'),
        transactionValue: 200,
        transactionType: 'W',
        categories: ['Groceries'],
        paymentMethod: 'Bank',
        deletedAt: new Date(),
      });

      const res = await request(app)
        .post(`/api/expenditures/${deletedExp._id}/restore`)
        .set('Authorization', viewerAuth);

      expect(res.status).toBe(403);
    });

    it('9. IDOR protection: User B cannot view User A deleted expenditures or restore User A deleted expenditure', async () => {
      const userAExp = await Expenditure.create({
        user: managerUser._id,
        date: new Date('2026-11-01'),
        transactionValue: 500,
        transactionType: 'W',
        categories: ['Dining'],
        paymentMethod: 'Bank',
        deletedAt: new Date(),
      });

      // User B lists deleted expenditures -> does not see User A's deleted record
      const listRes = await request(app)
        .get('/api/expenditures/deleted')
        .set('Authorization', otherAuth);
      expect(listRes.status).toBe(200);
      expect(listRes.body.data).toHaveLength(0);

      // User B attempts to restore User A's record -> HTTP 404
      const restoreRes = await request(app)
        .post(`/api/expenditures/${userAExp._id}/restore`)
        .set('Authorization', otherAuth);
      expect(restoreRes.status).toBe(404);
    });
  });

  describe('2. Trade Soft-Delete Recovery & Bridge Re-establishment', () => {
    it('10. GET /api/trades/deleted returns soft-deleted trades with pagination', async () => {
      const deletedTrade = await Trade.create({
        user: managerUser._id,
        type: 'Buy',
        stockCode: 'COMI',
        shares: 100,
        price: 80,
        totalValue: 8000,
        date: new Date('2026-11-01'),
        deletedAt: new Date(),
      });

      const res = await request(app)
        .get('/api/trades/deleted')
        .set('Authorization', managerAuth);

      expect(res.status).toBe(200);
      expect(res.body.data).toHaveLength(1);
      expect(res.body.data[0]._id.toString()).toBe(deletedTrade._id.toString());
      expect(res.body.total).toBe(1);
    });

    it('11. POST /api/trades/:id/restore restores soft-deleted trade and re-establishes linked bridge records [🟡-12]', async () => {
      // Create TopUp trade with sourceAccount: Bank
      const trade = await Trade.create({
        user: managerUser._id,
        type: 'TopUp',
        totalValue: 5000,
        date: new Date('2026-11-01'),
        sourceAccount: 'Bank',
        deletedAt: new Date(),
      });

      const restoreRes = await request(app)
        .post(`/api/trades/${trade._id}/restore`)
        .set('Authorization', managerAuth);

      expect(restoreRes.status).toBe(200);
      expect(restoreRes.body.msg).toBe('Trade restored successfully');

      // Verify trade is no longer deleted
      const refreshedTrade = await Trade.findById(trade._id);
      expect(refreshedTrade.deletedAt).toBeNull();

      // Verify linked expenditure bridge was re-created for TopUp
      const bridgeExp = await Expenditure.findOne({
        user: managerUser._id,
        linkedTradeId: trade._id,
        deletedAt: null,
      });
      expect(bridgeExp).not.toBeNull();
      expect(bridgeExp.transactionValue).toBe(5000);
      expect(bridgeExp.paymentMethod).toBe('Bank');
    });

    it('12. IDOR protection: User B cannot view or restore User A deleted trades', async () => {
      const tradeA = await Trade.create({
        user: managerUser._id,
        type: 'Buy',
        stockCode: 'SWDY',
        shares: 50,
        price: 40,
        totalValue: 2000,
        date: new Date('2026-11-01'),
        deletedAt: new Date(),
      });

      // User B lists deleted trades
      const listRes = await request(app)
        .get('/api/trades/deleted')
        .set('Authorization', otherAuth);
      expect(listRes.status).toBe(200);
      expect(listRes.body.data).toHaveLength(0);

      // User B attempts to restore User A trade -> HTTP 404
      const restoreRes = await request(app)
        .post(`/api/trades/${tradeA._id}/restore`)
        .set('Authorization', otherAuth);
      expect(restoreRes.status).toBe(404);
    });
  });
});
