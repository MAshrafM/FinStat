// backend/tests/integration/incomeBridge.test.js
const mongoose = require('mongoose');
const connectDB = require('../../config/db');
const User = require('../../models/User');
const Paycheck = require('../../models/Paycheck');
const Gold = require('../../models/Gold');
const Certificate = require('../../models/Certificate');
const Expenditure = require('../../models/Expenditure');
const {
  createExpenditureFromPaycheck,
  createExpenditureFromGoldSale,
  createExpenditureFromCertificatePayout,
  reverseIncomeExpenditure,
} = require('../../utils/incomeBridge');

jest.setTimeout(60000);

describe('Step 7B.1a: Income Settlement Bridge Integration Tests [FEAT-002, GAP-003]', () => {
  let testUser;

  beforeAll(async () => {
    await connectDB();

    await User.deleteMany({ username: 'income_bridge_user' });
    testUser = await User.create({
      username: 'income_bridge_user',
      email: 'income_bridge@finstat.io',
      password: 'HashedPassword123!',
      role: 'manager',
    });
  });

  beforeEach(async () => {
    delete process.env.ENABLE_UNIFIED_CASH_FLOW;
    await Expenditure.deleteMany({ user: testUser._id });
    await Paycheck.deleteMany({ user: testUser._id });
    await Gold.deleteMany({ user: testUser._id });
    await Certificate.deleteMany({ user: testUser._id });

    // Seed baseline initial balances: Bank = 5,000 EGP, Cash = 1,000 EGP, Prepaid = 500 EGP
    await Expenditure.create({
      user: testUser._id,
      date: new Date('2026-01-01T12:00:00Z'),
      transactionValue: 5000,
      transactionValueInPiastres: 500000,
      transactionType: 'T',
      paymentMethod: 'Bank',
      categories: ['Initial Balance'],
      bank: 5000,
      cash: 1000,
      prepaid: 500,
      bankInPiastres: 500000,
      cashInPiastres: 100000,
      prepaidInPiastres: 50000,
      runningBalances: { bank: 5000, cash: 1000, prepaid: 500 },
      runningBalancesInPiastres: { bank: 500000, cash: 100000, prepaid: 50000 },
    });
  });

  afterAll(async () => {
    if (testUser) {
      await Expenditure.deleteMany({ user: testUser._id });
      await Paycheck.deleteMany({ user: testUser._id });
      await Gold.deleteMany({ user: testUser._id });
      await Certificate.deleteMany({ user: testUser._id });
      await User.deleteMany({ _id: testUser._id });
    }
    delete process.env.ENABLE_UNIFIED_CASH_FLOW;
    await mongoose.connection.close();
  });

  test('1. createExpenditureFromPaycheck credits Bank by net salary (10,000 EGP) and sets linkedPaycheckId', async () => {
    const paycheck = await Paycheck.create({
      user: testUser._id,
      period: '2026-01',
      payDate: new Date('2026-01-25T12:00:00Z'),
      grossSalary: 12000,
      grossSalaryInPiastres: 1200000,
      netPay: 10000,
      netPayInPiastres: 1000000,
      type: 'Direct Deposit',
      disbursementType: 'Regular',
    });

    const exp = await createExpenditureFromPaycheck(paycheck, 'Bank', testUser._id);
    expect(exp).toBeDefined();
    expect(exp.transactionType).toBe('T');
    expect(exp.paymentMethod).toBe('Bank');
    expect(exp.transactionValue).toBe(10000);
    expect(exp.transactionValueInPiastres).toBe(1000000);
    expect(exp.categories).toEqual(['Salary']);
    expect(exp.linkedPaycheckId.toString()).toBe(paycheck._id.toString());
    expect(exp.autoGenerated).toBe(true);

    // Bank running balance should now be 5,000 + 10,000 = 15,000 EGP
    expect(exp.runningBalances.bank).toBe(15000);
    expect(exp.runningBalancesInPiastres.bank).toBe(1500000);

    // Verify foreign key saved back onto paycheck
    const refreshed = await Paycheck.findById(paycheck._id);
    expect(refreshed.linkedExpenditureId.toString()).toBe(exp._id.toString());
  });

  test('2. createExpenditureFromPaycheck credits Cash when destinationAccount is Cash', async () => {
    const paycheck = await Paycheck.create({
      user: testUser._id,
      period: '2026-02',
      payDate: new Date('2026-02-25T12:00:00Z'),
      grossSalary: 5000,
      grossSalaryInPiastres: 500000,
      netPay: 4500,
      netPayInPiastres: 450000,
      type: 'Cash',
      disbursementType: 'Regular',
    });

    const exp = await createExpenditureFromPaycheck(paycheck, 'Cash', testUser._id);
    expect(exp).toBeDefined();
    expect(exp.paymentMethod).toBe('Cash');
    expect(exp.transactionValue).toBe(4500);
    // Cash balance should be 1,000 + 4,500 = 5,500 EGP
    expect(exp.runningBalances.cash).toBe(5500);
    expect(exp.runningBalancesInPiastres.cash).toBe(550000);
  });

  test('3. createExpenditureFromPaycheck credits Prepaid when destinationAccount is Prepaid', async () => {
    const paycheck = await Paycheck.create({
      user: testUser._id,
      period: '2026-03',
      payDate: new Date('2026-03-25T12:00:00Z'),
      grossSalary: 2000,
      grossSalaryInPiastres: 200000,
      netPay: 2000,
      netPayInPiastres: 200000,
      type: 'Prepaid',
      disbursementType: 'Prepaid',
    });

    const exp = await createExpenditureFromPaycheck(paycheck, 'Prepaid', testUser._id);
    expect(exp).toBeDefined();
    expect(exp.paymentMethod).toBe('Prepaid');
    // Prepaid balance should be 500 + 2,000 = 2,500 EGP
    expect(exp.runningBalances.prepaid).toBe(2500);
    expect(exp.runningBalancesInPiastres.prepaid).toBe(250000);
  });

  test('4. createExpenditureFromGoldSale credits chosen account with gold proceeds (sellingPrice * weight)', async () => {
    const gold = await Gold.create({
      user: testUser._id,
      item: '24K Gold Bar 10g',
      karat: 24,
      weight: 10,
      price: 3000,
      paid: 30000,
      date: new Date('2026-01-10T12:00:00Z'),
      status: 'sold',
      sellingPrice: 3500,
      sellingPriceInPiastres: 350000,
      sellingDate: new Date('2026-02-10T12:00:00Z'),
    });

    // Proceeds = 10g * 3,500 EGP/g = 35,000 EGP (3,500,000 piastres)
    const exp = await createExpenditureFromGoldSale(gold, 'Cash', testUser._id);
    expect(exp).toBeDefined();
    expect(exp.paymentMethod).toBe('Cash');
    expect(exp.transactionValue).toBe(35000);
    expect(exp.transactionValueInPiastres).toBe(3500000);
    expect(exp.categories).toEqual(['Investment']);
    expect(exp.linkedGoldId.toString()).toBe(gold._id.toString());
    // Cash balance should be 1,000 + 35,000 = 36,000 EGP
    expect(exp.runningBalances.cash).toBe(36000);

    const refreshedGold = await Gold.findById(gold._id);
    expect(refreshedGold.linkedExpenditureId.toString()).toBe(exp._id.toString());
  });

  test('5. createExpenditureFromCertificatePayout credits Bank with principal + accrued interest', async () => {
    const cert = await Certificate.create({
      user: testUser._id,
      name: 'Platinum 3-Year Certificate',
      amount: 10000,
      amountInPiastres: 1000000,
      interest: 19,
      period: 36,
      startDate: new Date('2025-01-01T12:00:00Z'),
      status: 'withdrawn',
      withdrawalDate: new Date('2026-01-01T12:00:00Z'),
    });

    // Payout = 10,000 principal + 1,900 earned interest = 11,900 EGP
    const payoutInPiastres = 1190000;
    const exp = await createExpenditureFromCertificatePayout(cert, payoutInPiastres, 'Bank', testUser._id);
    expect(exp).toBeDefined();
    expect(exp.paymentMethod).toBe('Bank');
    expect(exp.transactionValue).toBe(11900);
    expect(exp.transactionValueInPiastres).toBe(1190000);
    expect(exp.linkedCertificateId.toString()).toBe(cert._id.toString());
    // Bank balance should be 5,000 + 11,900 = 16,900 EGP
    expect(exp.runningBalances.bank).toBe(16900);

    const refreshedCert = await Certificate.findById(cert._id);
    expect(refreshedCert.linkedExpenditureId.toString()).toBe(exp._id.toString());
  });

  test('6. reverseIncomeExpenditure soft-deletes linked Expenditure and rolls back balance on paycheck deletion', async () => {
    const paycheck = await Paycheck.create({
      user: testUser._id,
      period: '2026-04',
      payDate: new Date('2026-04-01T12:00:00Z'),
      grossSalary: 8000,
      grossSalaryInPiastres: 800000,
      netPay: 7000,
      netPayInPiastres: 700000,
      type: 'Direct Deposit',
      disbursementType: 'Regular',
    });

    const exp = await createExpenditureFromPaycheck(paycheck, 'Bank', testUser._id);
    expect(exp.runningBalances.bank).toBe(12000);

    // Now reverse/delete
    const reversed = await reverseIncomeExpenditure(paycheck.linkedExpenditureId, testUser._id);
    expect(reversed).toBeDefined();
    expect(reversed.deletedAt).not.toBeNull();

    // Verify subsequent expenditure calculation no longer includes the 7,000 EGP
    const checkExp = await Expenditure.create({
      user: testUser._id,
      date: new Date('2026-04-15T12:00:00Z'),
      transactionValue: 200,
      transactionValueInPiastres: 20000,
      transactionType: 'W',
      paymentMethod: 'Bank',
      categories: ['Groceries'],
      bank: 4800,
      cash: 1000,
      prepaid: 500,
      bankInPiastres: 480000,
      cashInPiastres: 100000,
      prepaidInPiastres: 50000,
      runningBalances: { bank: 4800, cash: 1000, prepaid: 500 },
      runningBalancesInPiastres: { bank: 480000, cash: 100000, prepaid: 50000 },
    });
    // Without the 7,000 EGP paycheck, balance starts at 5,000 - 200 = 4,800
    expect(checkExp.runningBalances.bank).toBe(4800);
  });

  test('7. reverseIncomeExpenditure reverts balance delta on gold sale status change from sold to hold', async () => {
    const gold = await Gold.create({
      user: testUser._id,
      item: 'Gold Coin',
      karat: 21,
      weight: 8,
      price: 3200,
      paid: 25600,
      date: new Date('2026-01-01T12:00:00Z'),
      status: 'sold',
      sellingPrice: 3500,
      sellingPriceInPiastres: 350000,
      sellingDate: new Date('2026-02-01T12:00:00Z'),
    });

    const exp = await createExpenditureFromGoldSale(gold, 'Cash', testUser._id);
    expect(exp).toBeDefined();

    const reversed = await reverseIncomeExpenditure(gold.linkedExpenditureId, testUser._id);
    expect(reversed).toBeDefined();
    expect(reversed.deletedAt).not.toBeNull();
  });

  test('8. reverseIncomeExpenditure reverts balance delta on certificate withdrawal cancellation', async () => {
    const cert = await Certificate.create({
      user: testUser._id,
      name: 'CD Payout Reversal Test',
      amount: 5000,
      amountInPiastres: 500000,
      interest: 10,
      period: 12,
      startDate: new Date('2025-01-01T12:00:00Z'),
      status: 'withdrawn',
    });

    const exp = await createExpenditureFromCertificatePayout(cert, 550000, 'Bank', testUser._id);
    expect(exp).toBeDefined();

    const reversed = await reverseIncomeExpenditure(cert.linkedExpenditureId, testUser._id);
    expect(reversed).toBeDefined();
    expect(reversed.deletedAt).not.toBeNull();
  });

  test('9. Bypass guard: when ENABLE_UNIFIED_CASH_FLOW=false, bridge returns null and creates 0 expenditures', async () => {
    process.env.ENABLE_UNIFIED_CASH_FLOW = 'false';

    const paycheck = await Paycheck.create({
      user: testUser._id,
      period: '2026-05',
      payDate: new Date('2026-05-01T12:00:00Z'),
      grossSalary: 6000,
      grossSalaryInPiastres: 600000,
      netPay: 5000,
      netPayInPiastres: 500000,
      type: 'Direct Deposit',
      disbursementType: 'Regular',
    });

    const exp = await createExpenditureFromPaycheck(paycheck, 'Bank', testUser._id);
    expect(exp).toBeNull();

    const expCount = await Expenditure.countDocuments({ user: testUser._id, linkedPaycheckId: paycheck._id });
    expect(expCount).toBe(0);
  });

  test('10. Idempotency: duplicate call with already-linked ID returns existing expenditure without double-crediting', async () => {
    const paycheck = await Paycheck.create({
      user: testUser._id,
      period: '2026-06',
      payDate: new Date('2026-06-01T12:00:00Z'),
      grossSalary: 10000,
      grossSalaryInPiastres: 1000000,
      netPay: 9000,
      netPayInPiastres: 900000,
      type: 'Direct Deposit',
      disbursementType: 'Regular',
    });

    const exp1 = await createExpenditureFromPaycheck(paycheck, 'Bank', testUser._id);
    expect(exp1).toBeDefined();

    // Call again with refreshed paycheck containing linkedExpenditureId
    const exp2 = await createExpenditureFromPaycheck(paycheck, 'Bank', testUser._id);
    expect(exp2).toBeDefined();
    expect(exp2._id.toString()).toBe(exp1._id.toString());

    // Verify only ONE linked expenditure exists for this paycheck
    const count = await Expenditure.countDocuments({ user: testUser._id, linkedPaycheckId: paycheck._id });
    expect(count).toBe(1);
  });

  test('11. Defensive Reversal: when reverseIncomeExpenditure is called with null or missing ID, completes safely', async () => {
    const res1 = await reverseIncomeExpenditure(null, testUser._id);
    expect(res1).toBeNull();

    const fakeId = new mongoose.Types.ObjectId();
    const res2 = await reverseIncomeExpenditure(fakeId, testUser._id);
    expect(res2).toBeNull();
  });
});

