// backend/utils/cardPaymentBridge.js
const mongoose = require('mongoose');
const Expenditure = require('../models/Expenditure');
const CardTransaction = require('../models/CardTransaction');
const CardPayment = require('../models/CardPayment');
const { toPiastres } = require('./currencyUtils');
const {
  calculateSignedDeltas,
  calculatePreviousBalance,
  propagateBalanceChanges,
} = require('./ledgerHelpers');

/**
 * Creates an Expenditure record when a credit card transaction (purchase / installment) is logged.
 * Credit card purchases are liabilities and do not impact ledger balances (bank, cash, prepaid).
 *
 * @param {Object} transaction - CardTransaction instance
 * @param {Object} card - CreditCard instance
 * @param {String|ObjectId} userId
 * @param {ClientSession|null} session
 * @returns {Promise<Expenditure|null>}
 */
const createExpenditureFromCardTransaction = async (transaction, card, userId, session = null) => {
  if (!transaction || transaction.createExpenditure === false) {
    return null;
  }

  // Check if an expenditure is already linked
  if (transaction.linkedExpenditureId) {
    const existingQuery = Expenditure.findOne({ _id: transaction.linkedExpenditureId, user: userId });
    if (session) existingQuery.session(session);
    const existing = await existingQuery;
    if (existing) return existing;
  }

  const txAmount = Number(transaction.amount) || 0;
  const txAmountInPiastres = transaction.amountInPiastres || toPiastres(txAmount);
  const txDate = new Date(transaction.date);

  // Carry forward previous running balances without alteration
  const prevBalances = await calculatePreviousBalance(userId, txDate, null, session);

  const newExpenditure = new Expenditure({
    user: userId,
    date: txDate,
    transactionValue: txAmount,
    transactionValueInPiastres: txAmountInPiastres,
    currency: transaction.currency || 'EGP',
    foreignAmount: transaction.foreignAmount || null,
    exchangeRateSnapshot: transaction.exchangeRateSnapshot || 1,
    transactionType: 'W',
    paymentMethod: 'Credit Card',
    categories: [transaction.category || 'Other'],
    description: transaction.description || `${card.name || 'Credit Card'} Purchase`,
    paidWithCreditCard: true,
    settledFromBank: false,
    settledAmountInPiastres: 0,
    settlementDate: null,
    linkedCardTransactionId: transaction._id,
    autoGenerated: true,
    bank: prevBalances.bank,
    cash: prevBalances.cash,
    prepaid: prevBalances.prepaid,
    bankInPiastres: prevBalances.bankInPiastres,
    cashInPiastres: prevBalances.cashInPiastres,
    prepaidInPiastres: prevBalances.prepaidInPiastres,
    runningBalances: {
      bank: prevBalances.bank,
      cash: prevBalances.cash,
      prepaid: prevBalances.prepaid,
    },
    runningBalancesInPiastres: {
      bank: prevBalances.bankInPiastres,
      cash: prevBalances.cashInPiastres,
      prepaid: prevBalances.prepaidInPiastres,
    },
  });

  await newExpenditure.save({ session });

  transaction.linkedExpenditureId = newExpenditure._id;
  await transaction.save({ session });

  return newExpenditure;
};

/**
 * Creates an Expenditure record when a credit card settlement/payment is logged.
 * Debits the source account (Bank, Cash, or Prepaid) and marks preceding purchases as settled.
 *
 * @param {Object} payment - CardPayment instance
 * @param {Object} card - CreditCard instance
 * @param {String|ObjectId} userId
 * @param {ClientSession|null} session
 * @returns {Promise<Expenditure|null>}
 */
const createExpenditureFromCardPayment = async (payment, card, userId, session = null) => {
  if (!payment || payment.createExpenditure === false) {
    return null;
  }

  if (payment.linkedExpenditureId) {
    const existingQuery = Expenditure.findOne({ _id: payment.linkedExpenditureId, user: userId });
    if (session) existingQuery.session(session);
    const existing = await existingQuery;
    if (existing) return existing;
  }

  const pAmount = Number(payment.amount) || 0;
  const pAmountInPiastres = payment.amountInPiastres || toPiastres(pAmount);
  const pDate = new Date(payment.date);
  const paymentSource = payment.paymentSource || 'Bank';

  const newExpenditure = new Expenditure({
    user: userId,
    date: pDate,
    transactionValue: pAmount,
    transactionValueInPiastres: pAmountInPiastres,
    transactionType: 'W',
    paymentMethod: paymentSource,
    categories: ['Credit Card Settlement'],
    description: `Settlement to ${card.name || 'Credit Card'}`,
    paidWithCreditCard: false,
    settledFromBank: true,
    settledAmountInPiastres: pAmountInPiastres,
    settlementDate: pDate,
    linkedCardPaymentId: payment._id,
    autoGenerated: true,
  });

  const prevBalances = await calculatePreviousBalance(userId, pDate, null, session);
  const deltas = calculateSignedDeltas(newExpenditure);

  const updatedRunningBalances = {
    bank: prevBalances.bank,
    cash: prevBalances.cash,
    prepaid: prevBalances.prepaid,
  };
  const updatedRunningBalancesInPiastres = {
    bank: prevBalances.bankInPiastres,
    cash: prevBalances.cashInPiastres,
    prepaid: prevBalances.prepaidInPiastres,
  };

  for (const { account, delta, deltaInPiastres } of deltas) {
    updatedRunningBalances[account] = (updatedRunningBalances[account] || 0) + delta;
    updatedRunningBalancesInPiastres[account] =
      (updatedRunningBalancesInPiastres[account] || 0) + deltaInPiastres;
  }

  newExpenditure.runningBalances = updatedRunningBalances;
  newExpenditure.runningBalancesInPiastres = updatedRunningBalancesInPiastres;
  newExpenditure.bank = updatedRunningBalances.bank;
  newExpenditure.cash = updatedRunningBalances.cash;
  newExpenditure.prepaid = updatedRunningBalances.prepaid;
  newExpenditure.bankInPiastres = updatedRunningBalancesInPiastres.bank;
  newExpenditure.cashInPiastres = updatedRunningBalancesInPiastres.cash;
  newExpenditure.prepaidInPiastres = updatedRunningBalancesInPiastres.prepaid;

  await newExpenditure.save({ session });

  await propagateBalanceChanges(userId, deltas, newExpenditure.date, newExpenditure._id, session);

  payment.linkedExpenditureId = newExpenditure._id;
  await CardPayment.updateOne(
    { _id: payment._id },
    { $set: { linkedExpenditureId: newExpenditure._id } },
    { session }
  );

  // Mark prior purchases as settled via FIFO
  await markPurchasesAsSettled(card, payment, userId, session);

  return newExpenditure;
};

/**
 * Sequentially marks preceding unsettled or partially settled purchases of a card
 * as settled up to the payment amount (Option A FIFO Linkage).
 *
 * @param {Object} card
 * @param {Object} payment
 * @param {String|ObjectId} userId
 * @param {ClientSession|null} session
 */
const markPurchasesAsSettled = async (card, payment, userId, session = null) => {
  const cardTxQuery = CardTransaction.find({
    card: card._id,
    user: userId,
    deletedAt: null,
  }).select('_id');
  if (session) cardTxQuery.session(session);
  const cardTransactions = await cardTxQuery;

  if (!cardTransactions || cardTransactions.length === 0) return;

  const txIds = cardTransactions.map((tx) => tx._id);
  const paymentDate = new Date(payment.date);

  const unpaidExpQuery = Expenditure.find({
    user: userId,
    paidWithCreditCard: true,
    settledFromBank: false,
    date: { $lte: paymentDate },
    linkedCardTransactionId: { $in: txIds },
    deletedAt: null,
  }).sort({ date: 1, _id: 1 });
  if (session) unpaidExpQuery.session(session);
  const unpaidExpenditures = await unpaidExpQuery;

  let remainingPaymentInPiastres = payment.amountInPiastres || toPiastres(payment.amount);

  for (const exp of unpaidExpenditures) {
    if (remainingPaymentInPiastres <= 0) break;

    const totalValInPiastres = exp.transactionValueInPiastres || toPiastres(exp.transactionValue);
    const alreadySettled = exp.settledAmountInPiastres || 0;
    const needed = totalValInPiastres - alreadySettled;

    if (needed <= 0) {
      exp.settledFromBank = true;
      await exp.save({ session });
      continue;
    }

    if (remainingPaymentInPiastres >= needed) {
      exp.settledAmountInPiastres = totalValInPiastres;
      exp.settledFromBank = true;
      exp.settlementDate = paymentDate;
      remainingPaymentInPiastres -= needed;
    } else {
      exp.settledAmountInPiastres = alreadySettled + remainingPaymentInPiastres;
      exp.settledFromBank = false;
      exp.settlementDate = paymentDate;
      remainingPaymentInPiastres = 0;
    }

    await exp.save({ session });
  }
};

/**
 * Preserves the audit trail when a card transaction or payment is deleted.
 * Unlinks the foreign key, sets autoGenerated = false, and appends an audit note.
 * Does NOT delete the expenditure or roll back bank running balance.
 *
 * @param {Object} cardEvent - CardTransaction or CardPayment
 * @param {String|ObjectId} userId
 * @param {ClientSession|null} session
 */
const unlinkExpenditure = async (cardEvent, userId, session = null) => {
  if (!cardEvent) return null;

  let query = { user: userId, deletedAt: null };
  if (cardEvent.linkedExpenditureId) {
    query._id = cardEvent.linkedExpenditureId;
  } else {
    query.$or = [
      { linkedCardTransactionId: cardEvent._id },
      { linkedCardPaymentId: cardEvent._id },
    ];
  }

  const expQuery = Expenditure.findOne(query);
  if (session) expQuery.session(session);
  const expenditure = await expQuery;
  if (!expenditure) return null;

  if (expenditure.linkedCardTransactionId && expenditure.linkedCardTransactionId.toString() === cardEvent._id.toString()) {
    expenditure.linkedCardTransactionId = null;
  }
  if (expenditure.linkedCardPaymentId && expenditure.linkedCardPaymentId.toString() === cardEvent._id.toString()) {
    expenditure.linkedCardPaymentId = null;
  }

  expenditure.autoGenerated = false;
  const auditNote = `[Auto-linked record deleted on ${new Date().toISOString().split('T')[0]}; expenditure retained for audit]`;
  expenditure.description = expenditure.description ? `${expenditure.description} ${auditNote}` : auditNote;

  await expenditure.save({ session });
  return expenditure;
};

module.exports = {
  createExpenditureFromCardTransaction,
  createExpenditureFromCardPayment,
  markPurchasesAsSettled,
  unlinkExpenditure,
};
